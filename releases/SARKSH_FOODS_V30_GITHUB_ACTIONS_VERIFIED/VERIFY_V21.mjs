import fs from 'node:fs';
import assert from 'node:assert/strict';
import crypto from 'node:crypto';
const read=(f)=>fs.readFileSync(f,'utf8');
const app=read('js/app.js');
const home=read('index.html'), products=read('products.html');
const names=['Chilli Powder','Turmeric Powder','Garam Masala','Curry Leaves Powder','Bitter Gourd Powder','Pulses Powder'];
for(const name of names) assert(app.includes(name),'Missing product '+name);
for(const p of ['index','story','products','quality','recipes','blog','contact']) assert(fs.existsSync(p+'.html'),p);
const img='assets/range-forest-dark-soil-v21.webp';
assert(fs.statSync(img).size>300000,'Approved full scenery photo missing / incomplete');
for(const f of ['assets/sarksh-original-logo.webp','assets/sarksh-original-emblem.webp','assets/golden-valley-v20-motion.webp','css/product-v19.css','css/product-v21.css','js/hero-v17.js']) assert(fs.statSync(f).size>100,f);
assert(app.includes('class="range-scene-photo"'),'Missing explicit image');
assert(app.split('class="range-scene-photo"').length===3,'Scenery image must appear on home and products page');
assert(app.indexOf('id="roots"')<app.indexOf('id="products"'),'Sourcing must come before product range');
assert(!app.includes('range-leaf-crown-left'),'Fragment overlays must be removed');
assert(home.includes('css/product-v21.css')&&products.includes('css/product-v21.css'),'V21 CSS missing');
assert(!home.includes('product-v20.css'),'Obsolete CSS still loaded');
assert(read('js/hero-v17.js').includes('golden-valley-v20-motion.webp'),'Hero asset changed');
console.log('V21 source QA passed: seven pages, six names, DOM-backed landscape on both pages, original hero and brand assets.');
